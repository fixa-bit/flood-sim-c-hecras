export type RiverId =
  | "indus"
  | "kabul"
  | "jhelum"
  | "chenab"
  | "ravi"
  | "sutlej";

export type StationKind = "dam" | "barrage" | "gauge";

export type FloodLimits = {
  /** FFD classes, lakh cusecs (1 lakh = 100,000 ft³/s) */
  low: number;
  medium: number;
  high: number;
  veryHigh: number;
  exceptional: number | null;
};

export type Station = {
  id: string;
  name: string;
  river: RiverId;
  riverName: string;
  lat: number;
  lon: number;
  kind: StationKind;
  designLakhCusec: number | null;
  limits: FloodLimits;
  /** Half-width of the analysis clip in degrees (~111 km at equator). */
  domainDeg: number;
  source: string;
};

